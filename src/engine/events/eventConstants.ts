/**
 * KAVACH Event Classification
 */

// 1. Domain Events (Business logic & transactions)
export const DOMAIN_EVENTS = {
  USER_REGISTERED: 'DOMAIN:USER_REGISTERED',
  USER_LOGGED_IN: 'DOMAIN:USER_LOGGED_IN',
  GUARDIAN_LINKED: 'DOMAIN:GUARDIAN_LINKED',
  GUARDIAN_UNLINKED: 'DOMAIN:GUARDIAN_UNLINKED',
  JOURNEY_STARTED: 'DOMAIN:JOURNEY_STARTED',
  JOURNEY_PROGRESS_UPDATED: 'DOMAIN:JOURNEY_PROGRESS_UPDATED',
  JOURNEY_COMPLETED: 'DOMAIN:JOURNEY_COMPLETED',
  JOURNEY_DEVIATED: 'DOMAIN:JOURNEY_DEVIATED',
  SOS_TRIGGERED: 'DOMAIN:SOS_TRIGGERED',
  SOS_CANCELLED: 'DOMAIN:SOS_CANCELLED',
  PROTECTION_STARTED: 'DOMAIN:PROTECTION_STARTED',
  PROTECTION_STOPPED: 'DOMAIN:PROTECTION_STOPPED',
  EVIDENCE_CAPTURED: 'DOMAIN:EVIDENCE_CAPTURED',
  EVIDENCE_UPLOADED: 'DOMAIN:EVIDENCE_UPLOADED',
} as const;

// 2. Application Events (UI orchestration & runtime updates)
export const APPLICATION_EVENTS = {
  THEME_CHANGED: 'APP:THEME_CHANGED',
  PROTECTION_SCORE_UPDATED: 'APP:PROTECTION_SCORE_UPDATED',
  UI_PANEL_OPENED: 'APP:UI_PANEL_OPENED',
  NOTIFICATION_RECEIVED: 'APP:NOTIFICATION_RECEIVED',
  SYNC_COMPLETED: 'APP:SYNC_COMPLETED',
} as const;

// 3. System Events (Hardware, OS & Telemetry)
export const SYSTEM_EVENTS = {
  BATTERY_LEVEL_CHANGED: 'SYSTEM:BATTERY_LEVEL_CHANGED',
  NETWORK_STATUS_CHANGED: 'SYSTEM:NETWORK_STATUS_CHANGED',
  GPS_ACCURACY_CHANGED: 'SYSTEM:GPS_ACCURACY_CHANGED',
  PERMISSION_STATUS_CHANGED: 'SYSTEM:PERMISSION_STATUS_CHANGED',
  APP_CRASH_RECOVERED: 'SYSTEM:APP_CRASH_RECOVERED',
  BACKGROUND_WORKER_PING: 'SYSTEM:BACKGROUND_WORKER_PING',
} as const;

export const ALL_EVENTS = {
  ...DOMAIN_EVENTS,
  ...APPLICATION_EVENTS,
  ...SYSTEM_EVENTS,
} as const;

export type KavachEventType = typeof ALL_EVENTS[keyof typeof ALL_EVENTS];

export interface KavachEvent<T = any> {
  id: string;
  type: KavachEventType;
  timestamp: number;
  payload: T;
  meta: {
    userId?: string;
    deviceId: string;
    version: string;
    tenantId?: string;
  };
}
